# Writes gen.ts's JSON as Kotlin sources: commonTest can't read files on wasm.
# The chat engine's part goes to kmp/shared (railstatus.chat.GoldenData, for EngineGoldenTest); the app's
# part (personal.ts, live.ts, client.ts's fakeFacts) stays here (railstatus.mobile.incident.GoldenData).
#   python3 write_kt.py golden.json ../GoldenData.kt ../../../../../../../../../kmp/shared/src/commonTest/kotlin/railstatus/chat/GoldenData.kt
import json, sys

ENGINE_KEYS = ['facts', 'trains', 'cases', 'helpers', 'clocks', 'adds', 'opens', 'llm', 'prompts', 'grounds', 'clusters', 'evalCases']

def esc(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '\\': out.append('\\\\')
        elif ch == '"': out.append('\\"')
        elif ch == '$': out.append('\\$')
        elif o < 0x20 or o in (0x2028, 0x2029, 0x7f): out.append('\\u%04x' % o)
        else: out.append(ch)
    return ''.join(out)

def write(path, package, what, data):
    src = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    N = 15000  # code points per chunk: at most 60 kB of UTF-8, under the JVM's 64 kB constant limit
    chunks = [src[i:i + N] for i in range(0, len(src), N)]
    with open(path, 'w', encoding='utf-8') as f:
        f.write('// GENERATED by golden/gen.ts and golden/write_kt.py (in native/composeApp/src/commonTest/kotlin/railstatus/mobile/incident). Do not edit.\n')
        f.write(f'// {what} as JSON.\n')
        f.write(f'package {package}\n\n')
        f.write('internal object GoldenData {\n')
        f.write('    val json: String get() = listOf(\n')
        for i in range(len(chunks)):
            f.write(f'        C{i},\n')
        f.write('    ).joinToString("")\n\n')
        for i, c in enumerate(chunks):
            f.write(f'    private const val C{i} = "{esc(c)}"\n')
        f.write('}\n')
    print(path, len(chunks), 'chunks')

golden = json.loads(open(sys.argv[1], encoding='utf-8').read())
write(sys.argv[2], 'railstatus.mobile.incident', "The TypeScript app's answers (mobile/src/incident/personal.ts, live.ts, client.ts)",
      {k: v for k, v in golden.items() if k not in ENGINE_KEYS})
write(sys.argv[3], 'railstatus.chat', "The TypeScript chat engine's answers (mobile/src/incident/chat/engine.ts)",
      {k: v for k, v in golden.items() if k in ENGINE_KEYS})
